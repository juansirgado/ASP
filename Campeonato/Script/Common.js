function styleButton(objButton,numStyle)
{
   if (numStyle == 0)
   {
      objButton.style.fontWeight        = 'bold';
      objButton.style.fontSize          = '12px';
      objButton.style.color             = '#FFFFFF';
      objButton.style.borderTopColor    = '#228822';
      objButton.style.borderRightColor  = '#228822';
      objButton.style.borderLeftColor   = '#228822';
      objButton.style.borderBottomColor = '#228822';
      objButton.style.paddingTop        = '4px';
      objButton.style.paddingRight      = '4px';
      objButton.style.paddingLeft       = '4px';
      objButton.style.paddingBottom     = '4px';
      objButton.style.backgroundColor   = '#228822';
   }
   else
   {
      objButton.style.fontWeight        = 'bold';
      objButton.style.fontSize          = '12px';
      objButton.style.color             = '#228822';
      objButton.style.borderTopColor    = '#FFFFFF';
      objButton.style.borderRightColor  = '#FFFFFF';
      objButton.style.borderLeftColor   = '#FFFFFF';
      objButton.style.borderBottomColor = '#FFFFFF';
      objButton.style.paddingTop        = '4px';
      objButton.style.paddingRight      = '4px';
      objButton.style.paddingLeft       = '4px';
      objButton.style.paddingBottom     = '4px';
      objButton.style.backgroundColor   = '#FFFFFF';
   }
}
